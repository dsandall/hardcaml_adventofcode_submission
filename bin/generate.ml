open! Core
open! Hardcaml

(*import our design source as a library (named in src/dune)*)
open! Hardcaml_advent_d1

(*actual hardcaml packaging stuff*)
let generate_range_finder_rtl () =
  (* a Circuit takes output (and usually) signals, and ensures it can be generated as hardware*)
  (* also can be used to name ports (if not using an interface) *)
  (* the equivalent of a Module in verilog*)
  let module C = Circuit.With_interface (Zero_dial.I) (Zero_dial.O) in
  (* a Scope is a mutable object passed between Circuits that forms a complete Hardcaml design*)
  (* controls design heirarchy, elaboration, subcircuits*)
  (* NOTE: https://www.janestreet.com/web-app/hardcaml-docs/using-interfaces/scopes *)
  let scope = Scope.create ~auto_label_hierarchical_ports:true () in
  let circuit = C.create_exn ~name:"range_finder_top" (Zero_dial.hierarchical scope) in
  (* Transforming the Scope to RTL*)
  let rtl_circuits =
    Rtl.create ~database:(Scope.circuit_database scope) Verilog [ circuit ]
  in
  (* printing to output*)
  let rtl = Rtl.full_hierarchy rtl_circuits |> Rope.to_string in
  print_endline rtl
;;

(* defining the functionality of the subcommand*)
let range_finder_rtl_command =
  (* command definition function - accepts: (help text) (parameters) (handler function)*)
  Command.basic (*--help text*)
    ~summary:"outputs the verilog for the range finder module"
    (*fp magic, dont worry about it*)
    [%map_open.Command
      (*no parameters*)
      let () = return () in
      (*handler is:*)
      fun () -> generate_range_finder_rtl ()]
;;

(* let () = means run and disregard, eg, run code "for side effects, not the value" *)
(* in this case, this block is just defining the entry point of the executable generated by all this code*)
(* the executable's only actual job is to output the RTL - i'm assuming the hardware is made at compile time, and the exe just spits out text?*)
let () =
  Command_unix.run
    (Command.group
     (* define subcommands for this executable, pass a tuple containing the command parameters*)
       ~summary:"here are all the subcommands for this executable" (*--help text*)
       [ "range-finder", range_finder_rtl_command ])
;;
